from rest_framework import serializers

from .models import Department, Employee


class DepartmentSerializer(serializers.ModelSerializer):
    class Meta:
        model = Department
        fields = ('id', 'name', 'created_at')
        read_only_fields = ('id', 'created_at')


class EmployeeSerializer(serializers.ModelSerializer):
    # Output only: shows the department name next to the department id.
    department_name = serializers.CharField(source='department.name', read_only=True)

    class Meta:
        model = Employee
        fields = (
            'id',
            'name',
            'email',
            'department',
            'department_name',
            'created_by',
            'created_at',
        )
        # read_only_fields: these are ignored if a client sends them.
        # - id / created_at are generated by the database.
        # - created_by must not be chosen by the client (they could pretend to
        #   be another user). A later phase will set it from request.user.
        read_only_fields = ('id', 'created_by', 'created_at')
        # Drop DRF's automatic UniqueValidator for email. It is case-sensitive
        # and would run before validate_email, hiding our error message.
        # validate_email below does the uniqueness check instead.
        extra_kwargs = {'email': {'validators': []}}

    def validate_email(self, value):
        # Case-insensitive uniqueness check: "Sara@x.com" and "sara@x.com"
        # count as the same email. The value itself is stored as typed.
        employees = Employee.objects.filter(email__iexact=value)
        # On update, ignore the employee being edited so it can keep its own email.
        if self.instance is not None:
            employees = employees.exclude(pk=self.instance.pk)
        if employees.exists():
            raise serializers.ValidationError('An employee with this email already exists.')
        return value
